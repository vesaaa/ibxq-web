#!/usr/bin/env python3
"""Download font subsets that contain only the characters used in index.html.

Run this again whenever you change the page text, otherwise new characters
fall back to the system font:

    python3 scripts/build-fonts.py

Uses the Google Fonts `text=` API, so no extra Python packages are needed.
"""
import pathlib, re, urllib.parse, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "fonts"
UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36"

# (CSS family name, Google Fonts axis spec, style, weight, file stem)
FACES = [
    ("Noto Serif SC",  "wght@600",     "normal", 600, "noto-serif-sc-600"),
    ("Noto Serif SC",  "wght@900",     "normal", 900, "noto-serif-sc-900"),
    ("Noto Sans SC",   "wght@400",     "normal", 400, "noto-sans-sc-400"),
    ("Newsreader",     "ital,wght@1,400", "italic", 400, "newsreader-italic-400"),
    ("JetBrains Mono", "wght@400",     "normal", 400, "jetbrains-mono-400"),
    ("JetBrains Mono", "wght@500",     "normal", 500, "jetbrains-mono-500"),
]

def page_chars():
    text = (ROOT / "index.html").read_text(encoding="utf-8")
    chars = set(chr(c) for c in range(0x20, 0x7F))          # all printable ASCII
    chars |= {ch for ch in text if ord(ch) > 0x7F}          # every non-ASCII char on the page
    return "".join(sorted(chars))

def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()

def main():
    FONT_DIR.mkdir(exist_ok=True)
    text = page_chars()
    css_out = ["/* Generated by scripts/build-fonts.py — do not edit by hand. */"]
    for family, axes, style, weight, stem in FACES:
        q = urllib.parse.urlencode({"family": f"{family}:{axes}", "text": text, "display": "swap"})
        css = get("https://fonts.googleapis.com/css2?" + q).decode()
        urls = re.findall(r"src:\s*url\(([^)]+)\)", css)
        if len(urls) != 1:
            raise SystemExit(f"{family} {axes}: expected 1 font file, got {len(urls)}")
        data = get(urls[0])
        (FONT_DIR / f"{stem}.woff2").write_bytes(data)
        print(f"{stem}.woff2  {len(data)/1024:.0f} KB")
        css_out.append(
            "@font-face{"
            f"font-family:'{family}';font-style:{style};font-weight:{weight};font-display:swap;"
            f"src:url('/fonts/{stem}.woff2') format('woff2')"
            "}"
        )
    (FONT_DIR / "fonts.css").write_text("\n".join(css_out) + "\n", encoding="utf-8")
    print(f"{len(text)} characters, fonts.css written")

if __name__ == "__main__":
    main()
